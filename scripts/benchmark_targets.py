#!/usr/bin/env python3
"""Instrument and report the 12 performance targets from the 24 Nov research.

This is a static evidence harness: it checks that each target has a concrete
implementation marker and, where available, a passing test marker. It does not
claim runtime proof. Targets with no markers are reported Unverified, never
silently upgraded to Verified.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
APP = Path(r"C:\Users\jpowe\Desktop\projects\polsia free v1\app")
OUT = REPO / "docs" / "BENCHMARK-REPORT.md"

# (id, target, [(root, relative path, marker), ...], test marker or None)
TARGETS = [
    ("unauthorised-financial-actions", "zero", [
        ("app", "bridge/payments.py", "confirm"),
        ("app", "src/studio.js", "HUMAN_GATES"),
    ], ("app", "tests/smoke.test.js", "human gate")),
    ("cross-company-data-leakage", "zero in security tests", [
        ("app", "src/companies.js", "namespace"),
        ("app", "src/actions.js", "company"),
    ], None),
    ("duplicate-payment-execution", "zero in retry tests", [
        ("app", "bridge/server.py", "idem_key"),
    ], ("app", "bridge/test_idempotency.py", "idempotency")),
    ("critical-workflow-recovery", "100% in defined failure scenarios", [
        ("app", "src/mechanisms.js", "maxRetries"),
        ("app", "src/actions.js", "bus"),
    ], None),
    ("routine-task-completion", ">=95% on a defined benchmark", [
        ("app", "src/solo.js", "runTask"),
    ], ("app", "tests/smoke.test.js", "runTask")),
    ("critical-security-vulnerabilities", "zero known unresolved at release", [], None),
    ("external-actions-recorded", "100%", [
        ("app", "bridge/server.py", "def audit"),
    ], None),
    ("budget-limit-enforcement", "100% in policy tests", [
        ("app", "src/treasury.js", "limit"),
        ("app", "src/governance.js", "budget"),
    ], None),
    ("failed-deployment-recovery", "tested automated rollback", [
        ("app", "package.json", "snapshot-dist"),
        ("repo", "scripts/rollback_build.py", "dist.previous"),
    ], None),
    ("offline-capability", "defined core workflows remain available", [
        ("app", "bridge/client.js", "No bridge configured"),
        ("app", "src/actions.js", "localStorage"),
    ], None),
    ("data-portability", "successful export and restoration", [
        ("app", "src/data-ownership.js", "exportSnapshot"),
    ], None),
    ("provider-independence", "multiple interchangeable providers", [
        ("app", "src/registries.js", "ENGINES"),
        ("app", "src/models.js", "Ollama"),
    ], ("app", "tests/smoke.test.js", "assignEngine")),
]


def read(root: str, rel: str) -> str:
    base = APP if root == "app" else REPO
    path = base / rel
    try:
        return path.read_text(encoding="utf-8", errors="ignore").lower()
    except OSError:
        return ""


def classify(found: int, total: int, test_ok: bool) -> str:
    if total == 0 or found == 0:
        return "Unverified"
    if found < total:
        return "Partial"
    return "Verified" if test_ok else "Implemented"


def main() -> None:
    rows = []
    for tid, target, markers, test in TARGETS:
        hits = []
        for root, rel, marker in markers:
            text = read(root, rel)
            hits.append(f"`{rel}` {'yes' if marker.lower() in text else 'no'}")
        found = sum(h.endswith("yes") for h in hits)
        test_ok = False
        if test:
            t_root, t_rel, t_marker = test
            test_ok = t_marker.lower() in read(t_root, t_rel)
        rows.append((tid, target, classify(found, len(markers), test_ok),
                     ", ".join(hits) if hits else "no implementation marker",
                     "yes" if test_ok else "no"))

    counts: dict[str, int] = {}
    for row in rows:
        counts[row[2]] = counts.get(row[2], 0) + 1

    lines = [
        "# Performance benchmark report",
        "",
        "Generated by `scripts/benchmark_targets.py` from the 12 targets in the "
        "24 November 2026 research. This is a **static evidence harness**: it "
        "checks that implementation and test markers exist. It does not measure "
        "runtime behaviour, and a marker is never upgraded to Verified without "
        "a matching test marker.",
        "",
        "## Summary",
        "",
        "| Classification | Count |",
        "|---|---:|",
    ]
    for cls in sorted(counts):
        lines.append(f"| {cls} | {counts[cls]} |")
    lines += [
        "",
        "| Target | Proposed target | Status | Implementation evidence | Test marker |",
        "|---|---|---|---|---|",
    ]
    for tid, target, status, evidence, test_ok in rows:
        lines.append(f"| `{tid}` | {target} | {status} | {evidence} | {test_ok} |")
    lines += [
        "",
        "## Interpretation",
        "",
        "- **Unverified** targets have no marker or no test. They are gaps in "
        "measurement, not claims of failure.",
        "- **Implemented** targets have implementation markers but no matching "
        "test marker; add an acceptance test to reach Verified.",
        "- The proposed percentages are research targets, not certified results. "
        "An independent OWASP Top 10 for Agentic Applications review remains a "
        "human/external task.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO)}: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()
