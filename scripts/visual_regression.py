#!/usr/bin/env python3
"""Visual regression for Polsia Free v1.

Captures the built site with local Edge at three widths, compares each route to
a stored baseline, and writes a report with similarity floors. `--baseline`
(captures the current build as the baseline. The dashboard is also compared to
the supplied attachments/picture-1.png at its native capture size.

Usage:
  python scripts/visual_regression.py --baseline
  python scripts/visual_regression.py
"""
from __future__ import annotations

import argparse
import functools
import os
import threading
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
WORKSPACE = Path(os.environ.get("PFV1_WORKSPACE", r"C:\Users\jpowe\Desktop\projects\polsia free v1"))
DIST = WORKSPACE / "app" / "dist"
BASELINE = REPO / "tests" / "visual" / "baseline"
REPORT = REPO / "docs" / "VISUAL-REGRESSION.md"
REFERENCE_DASH = WORKSPACE / "attachments" / "picture-1.png"

ROUTES = [
    ("start", ""),
    ("privacy", "privacy"),
    ("new", "new"),
    ("terms", "terms"),
    ("about", "about"),
    ("dashboard", "dashboard/pagemurmur-9jsvs1"),
]
PUBLIC_WIDTHS = [1440, 768, 390]
FLOORS = {"public": 99.0, "dashboard": 90.0}
TARGET_DASHBOARD = 95.0


class Quiet(SimpleHTTPRequestHandler):
    def log_message(self, *_args):
        pass


def similarity(a: Path, b: Path) -> float:
    from PIL import Image, ImageChops, ImageStat
    with Image.open(a) as ia, Image.open(b) as ib:
        left = ia.convert("RGB")
        right = ib.convert("RGB")
        if left.size != right.size:
            right = right.resize(left.size)
        diff = ImageChops.difference(left, right)
        mean = sum(ImageStat.Stat(diff).mean) / 3
        return round(max(0.0, 1 - mean / 255) * 100, 2)


def capture(root: str) -> dict[tuple[str, int], Path]:
    from playwright.sync_api import sync_playwright
    captured: dict[tuple[str, int], Path] = {}
    handler = functools.partial(Quiet, directory=str(DIST))
    server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    port = server.server_address[1]
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(channel="msedge", headless=True)
            for name, route in ROUTES:
                widths = [(1668, 925)] if name == "dashboard" else [(w, 900) for w in PUBLIC_WIDTHS]
                for width, height in widths:
                    page = browser.new_page(viewport={"width": width, "height": height})
                    page.goto(f"http://127.0.0.1:{port}/{route}/", wait_until="networkidle", timeout=60000)
                    out = Path(root) / f"{name}-{width}.png"
                    page.screenshot(path=str(out))
                    captured[(name, width)] = out
                    page.close()
            browser.close()
    finally:
        server.shutdown()
        server.server_close()
    return captured


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", action="store_true", help="capture the current build as the baseline")
    args = ap.parse_args()

    if not DIST.exists():
        raise SystemExit(f"Build not found: {DIST} (run npm run build first)")
    BASELINE.mkdir(parents=True, exist_ok=True)
    tmp = BASELINE / "_current"
    tmp.mkdir(parents=True, exist_ok=True)
    shots = capture(str(tmp))

    rows = []
    for (name, width), shot in sorted(shots.items()):
        base = BASELINE / f"{name}-{width}.png"
        if args.baseline:
            shot.replace(base)
            rows.append((name, width, "baseline saved", "-"))
            continue
        if not base.exists():
            rows.append((name, width, "no baseline", "Missing"))
            continue
        score = similarity(shot, base)
        floor = FLOORS["dashboard" if name == "dashboard" else "public"]
        rows.append((name, width, f"{score}%", "PASS" if score >= floor else "FAIL"))

    dash_ref = ""
    if REFERENCE_DASH.exists() and ("dashboard", 1668) in shots:
        dash_score = similarity(REFERENCE_DASH, shots[("dashboard", 1668)])
        dash_ref = (f"{dash_score}% vs supplied picture-1.png "
                    f"(floor {FLOORS['dashboard']}%, target {TARGET_DASHBOARD}%)")

    lines = [
        "# Visual regression report",
        "",
        f"Generated by `scripts/visual_regression.py` from `{DIST.relative_to(WORKSPACE)}`. "
        "Baseline mode: `--baseline`. Local Edge, no remote service, no credentials.",
        "",
        f"Dashboard reference: {dash_ref or 'not available'}",
        "",
        "| Route | Width | Similarity | Result |",
        "|---|---:|---:|---|",
    ]
    for name, width, score, result in rows:
        lines.append(f"| {name} | {width} | {score} | {result} |")
    lines += [
        "",
        "Public pages use a 99% floor; the authenticated dashboard uses 90% "
        "until typography reaches the 95% target. A missing baseline is a gap, "
        "not a pass.",
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {REPORT.relative_to(REPO)}: {len(rows)} captures")

    for child in tmp.iterdir():
        child.unlink()
    try:
        tmp.rmdir()
    except OSError:
        pass


if __name__ == "__main__":
    main()
